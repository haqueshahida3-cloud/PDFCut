export const LANGUAGES: LanguageInfo[] = RAW.map(([code, name, english]) => ({ code, name, english }));

const RTL_BASES = new Set(['ar', 'ur', 'he', 'fa', 'ps', 'sd', 'ckb', 'ug', 'yi', 'dv']);
export const RTL_CODES = new Set(LANGUAGES.filter((l) => RTL_BASES.has(l.code.split('-')[0]) && l.code !== 'ku').map((l) => l.code));

/** Maps a browser language tag (e.g. "pt-PT", "zh") to the closest supported code. */
export function resolveLanguage(tag: string): string {
  const t = tag.toLowerCase();
  const exact = LANGUAGES.find((l) => l.code.toLowerCase() === t);
  if (exact) return exact.code;
  const base = t.split('-')[0];
  return LANGUAGES.find((l) => l.code.toLowerCase() === base)?.code ?? 'en';
}
