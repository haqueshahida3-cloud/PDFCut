// Builds the command line for the packaged app:
//   dist-electron/cli.cjs       the whole CLI bundled (also used by the desktop app for file-manager actions)
//   dist-electron/cli-main.cjs  entry point run by the /usr/bin/pdfcut launcher with ELECTRON_RUN_AS_NODE=1
// The two files are copied to the app's resources/cli folder by electron-builder (see electron-builder.yml).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

mkdirSync('dist-electron', { recursive: true });

await build({
  entryPoints: ['src/cli/run.ts'],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  outfile: 'dist-electron/cli.cjs',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
});

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
writeFileSync(
  'dist-electron/cli-main.cjs',
  `'use strict';
// PDFCut command line entry (generated by scripts/build-electron.mjs).
const { runCli } = require('./cli.cjs');
runCli(process.argv.slice(2), { version: ${JSON.stringify(version)} }).then((code) => {
  process.exitCode = code;
});
`,
);

console.log('Built dist-electron/cli.cjs and dist-electron/cli-main.cjs');
